def heading(lang, title):
    if lang == 'de':
        return DE_HEADINGS[title]
    if lang == 'tr':
        # Turkse i: I wordt ı en İ wordt i (en andersom bij de hoofdletter).
        t = title.replace('I', 'ı').replace('İ', 'i').lower()
        first = {'i': 'İ', 'ı': 'I'}.get(t[:1], t[:1].upper())
        return first + t[1:]
    t = title.lower()
    return t[:1].upper() + t[1:]


